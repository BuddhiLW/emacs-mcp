(ns hive-mcp.hivemind.conversation
  "Inter-Ling Conversation Protocol — pure protocol layer (Calculations).

   Implements the three primitives from decision 20260401222011-493b1a6e:
     - tell    : fire-and-forget DM         (no correlation, no blocking)
     - ask     : DM that blocks the sender  (correlated via :ask-id → promise-chan)
     - respond : answer to a prior ask      (delivers a value to the ask's promise-chan)

   Stratification (decision 20260415135102-1d300fdc):
     - This namespace is Calculations + a tiny Data layer (the pending-asks
       atom). It does NOT call NATS, the bounded-atom registry, the
       event-bus, or any IO boundary. Effect handlers are responsible for
       transport and persistence.
     - The public functions return *event maps* (envelopes), the caller
       (interceptors / event handlers) are responsible for dispatching
       them onto the bus.
     - `register-ask!` / `deliver-response!` / `cancel-ask!` operate on a
       defonce'd atom. This is the only mutable state in the protocol layer
       and is bounded by sweep + per-call dissoc.

   ask-id correlation:
     A `random-uuid` string is generated by the sender. The ask map is parked
     under `pending-asks` with a one-shot core.async promise-chan. The receiver
     calls `deliver-response!` with the same ask-id — the value lands on the
     promise-chan and the sender's parked `alt!!` returns. On timeout the
     entry is dissoc'd and the response (if it ever arrives) is dropped.

   Why promise-chan (not NATS req-reply)?
     - Local-first: works without a backbone. NATS bridge merely re-injects
       respond messages into deliver-response! so the same correlation table
       handles both transports.
     - Cancellable + timeout-safe via core.async/alt!!.
     - Mirrors existing hivemind.messaging/ask! shape for the human-loop case.
     - One mechanism, two transports — matches Stratification."

  (:require [clojure.core.async :as async :refer [alt!! timeout]]
            [taoensso.timbre :as log]))
