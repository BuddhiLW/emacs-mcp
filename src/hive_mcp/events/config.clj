(ns hive-mcp.events.config
  "Typed config for hive-mcp.events.core via hive-di defconfig.

   Replaces:
     - `defonce *metrics-config (atom default-metrics-config)` (mutable global)
       in hive-mcp.events.core, with two `HIVE_EVENTS_METRICS_*` env-overridable
       fields.
     - 4 raw `(System/getenv \"CLAUDE_SWARM_*\")` calls inside the `:agent-context`
       coeffect, with a typed `EventsAgentConfig`.

   Resolution order (per field): override > env > default.

   Tests can override the resolver via with-redefs:

     (with-redefs [hive-mcp.events.config/metrics-config
                   (fn [] {:max-timings 10 :max-timings-per-type 5})]
       ...)

   Generated by defconfig (per record):
     <Name>             — ADT
     <Name>-fields      — field registry
     <Name>-schema      — Malli schema
     resolve-<Name>     — resolver fn (0/1/2 arity, returns Result)"
  (:require [hive-di.core :refer [defconfig env]]
            [hive-dsl.result :as r]))
